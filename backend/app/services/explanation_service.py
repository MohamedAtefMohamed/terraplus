"""AI-assisted (and fully deterministic) explanation engine.

The deterministic engine is the product default: it converts the analysis JSON
into a structured, cautious explanation without any external service. An optional
OpenAI-compatible LLM may rewrite four narrative fields; it never replaces the
underlying observations, statistics, quality or limitations.
"""

from __future__ import annotations

import json
import logging
from typing import Any

import httpx

from app.core.config import get_settings
from app.db.models import Analysis, Location, Observation

logger = logging.getLogger(__name__)


def _date(value: Any) -> str:
    try:
        return value.date().isoformat()
    except Exception:
        return str(value)


def _deterministic(
    analysis: Analysis, before: Observation, after: Observation, location: Location
) -> dict[str, Any]:
    stats = analysis.stats or {}
    quality = analysis.quality or {}
    net = float(stats.get("net_water_change_km2", 0.0))
    gain = float(stats.get("water_gain_km2", 0.0))
    loss = float(stats.get("water_loss_km2", 0.0))
    changed_pct = float(stats.get("changed_fraction", 0.0)) * 100
    before_date = _date(before.acquired_at)
    after_date = _date(after.acquired_at)

    if net > 0.05:
        headline = (
            f"Low-backscatter water indicator expanded by {net:.2f} km² between "
            f"{before_date} and {after_date}"
        )
        direction = "expanded"
    elif net < -0.05:
        headline = (
            f"Low-backscatter water indicator contracted by {abs(net):.2f} km² between "
            f"{before_date} and {after_date}"
        )
        direction = "contracted"
    else:
        headline = f"Mixed radar backscatter change detected between {before_date} and {after_date}"
        direction = "was approximately balanced"

    observations = [
        f"Earlier scene: {before_date}, {before.mission}, {before.polarization} polarization, {before.resolution_m:.0f} m grid.",
        f"Later scene: {after_date}, {after.mission}, {after.polarization} polarization, {after.resolution_m:.0f} m grid.",
        f"{changed_pct:.1f}% of valid pixels changed by more than ±{analysis.change_threshold_db:.1f} dB, covering {analysis.change_area_km2:.2f} km².",
        f"Pixels below the {analysis.water_threshold_db:.1f} dB water-indicator threshold: {float(stats.get('water_before_fraction', 0)) * 100:.1f}% before and {float(stats.get('water_after_fraction', 0)) * 100:.1f}% after.",
        f"Water-indicator gain: {gain:.2f} km²; loss: {loss:.2f} km²; net change: {net:+.2f} km².",
        f"Valid-pixel coverage: {float(stats.get('valid_coverage', 0)) * 100:.1f}%. Processing quality: {analysis.confidence_label} ({analysis.confidence_score:.2f}).",
    ]
    if analysis.is_synthetic:
        observations.append(
            "Both scenes are synthetic demonstration GeoTIFFs generated by TerraPulse; the pixels are not a NASA acquisition."
        )

    interpretation = (
        f"The analysis shows that the low-backscatter water indicator {direction}. "
        "In a wetland or delta setting this pattern can be consistent with a change in "
        "surface water, wet soil or vegetation structure. It is also possible for smoother "
        "bare ground, harvest/tillage, radar shadow, or differences in acquisition geometry "
        "to produce a similar radiometric signature. Establishing a cause requires comparison "
        "with independent observations such as optical imagery, water-level records or field data."
    )
    if analysis.is_synthetic:
        interpretation += (
            " Because these are generated scenes, this explanation describes the demonstration "
            "dataset only and must not be read as an environmental finding for the real location."
        )

    environmental_relevance = (
        f"{location.name} ({location.region}) is presented as a {location.focus.lower()} "
        "monitoring scenario. SAR is valuable in this context because radar can observe "
        "surface structure through cloud and at night, which complements optical imagery. "
        "The demonstration shows how a change signal can be surfaced and explained; it does "
        "not quantify hazard, damage or ecological impact."
    )

    return {
        "mode": "deterministic",
        "engine": "TerraPulse rule-based explanation engine v1.0",
        "headline": headline,
        "summary": analysis.summary,
        "observations": observations,
        "interpretation": interpretation,
        "environmental_relevance": environmental_relevance,
        "technical_indicators": [
            {
                "label": "Changed area",
                "value": analysis.change_area_km2,
                "unit": "km²",
                "meaning": "Area above the configurable backscatter-change threshold; not a flood extent.",
            },
            {
                "label": "Water-indicator gain",
                "value": gain,
                "unit": "km²",
                "meaning": "Pixels that became low-backscatter between the two observations.",
            },
            {
                "label": "Water-indicator loss",
                "value": loss,
                "unit": "km²",
                "meaning": "Pixels that stopped being low-backscatter between the two observations.",
            },
            {
                "label": "Mean change",
                "value": stats.get("mean_change_db"),
                "unit": "dB",
                "meaning": "Mean per-pixel difference (later minus earlier) across valid pixels.",
            },
            {
                "label": "Residual noise estimate",
                "value": quality.get("difference_noise_db"),
                "unit": "dB",
                "meaning": "Robust MAD-based noise estimate among low-change pixels.",
            },
        ],
        "confidence": {
            "label": analysis.confidence_label,
            "score": analysis.confidence_score,
            "rationale": quality.get("score_meaning"),
            "important": (
                "This score reflects processing quality (coverage, noise, alignment). It is not "
                "the probability that a flood or other event occurred."
            ),
        },
        "method": {
            "name": "Threshold-based backscatter difference with a low-backscatter water indicator",
            "change_threshold_db": analysis.change_threshold_db,
            "water_threshold_db": analysis.water_threshold_db,
            "steps": [
                "Load both georeferenced rasters and validate nodata / value ranges.",
                "Confirm identical grid, CRS and geotransform.",
                "Apply a small median filter to reduce speckle for screening.",
                "Compute per-pixel dB difference (later minus earlier).",
                "Classify increase / decrease beyond the configurable threshold.",
                "Derive low-backscatter water-indicator masks and their gain/loss.",
                "Compute spatial statistics, quality indicators and vector outlines.",
            ],
        },
        "analysis_period": {
            "before": before_date,
            "after": after_date,
            "before_observation_id": before.id,
            "after_observation_id": after.id,
        },
        "source_data": [
            {
                "role": "earlier",
                "observation_id": before.id,
                "external_id": before.external_id,
                "mission": before.mission,
                "instrument": before.instrument,
                "product_type": before.product_type,
                "acquired_at": before.acquired_at.isoformat(),
                "data_mode": before.data_mode,
                "is_synthetic": before.is_synthetic,
                "source_name": before.source_name,
                "source_url": before.source_url,
            },
            {
                "role": "later",
                "observation_id": after.id,
                "external_id": after.external_id,
                "mission": after.mission,
                "instrument": after.instrument,
                "product_type": after.product_type,
                "acquired_at": after.acquired_at.isoformat(),
                "data_mode": after.data_mode,
                "is_synthetic": after.is_synthetic,
                "source_name": after.source_name,
                "source_url": after.source_url,
            },
        ],
        "uncertainty": analysis.limitations,
        "limitations": analysis.limitations,
        "sources": [
            {
                "name": "NASA NISAR mission",
                "url": "https://science.nasa.gov/mission/nisar/",
                "note": "Mission context and integration target.",
            },
            {
                "name": "ASF DAAC search",
                "url": "https://search.asf.alaska.edu/",
                "note": "Live NISAR granule metadata discovery adapter.",
            },
            {
                "name": "TerraPulse synthetic demo generator",
                "url": None,
                "note": "Source of the synthetic demonstration scenes used in this analysis.",
            }
            if analysis.is_synthetic
            else {
                "name": "Staged observation source",
                "url": None,
                "note": "Attribution is recorded on the observation record.",
            },
        ],
        "disclaimer": (
            "Automated explanation of a demonstration analysis. Not a scientific finding, "
            "flood map, emergency product or validated hazard assessment."
        ),
    }


async def _try_llm(
    payload: dict[str, Any], analysis: Analysis
) -> tuple[dict[str, Any] | None, str | None]:
    settings = get_settings()
    if not settings.has_llm_credentials:
        return None, None

    system_prompt = (
        "You are a careful remote-sensing analyst writing for a non-specialist audience. "
        "You will receive a JSON analysis of two SAR scenes. Rewrite ONLY the fields "
        "'headline', 'summary', 'interpretation' and 'environmental_relevance'. "
        "Rules: distinguish measured observations from interpretation; use 'may be consistent with', "
        "never assert a cause; never claim a flood or disaster occurred; do not invent numbers; "
        "mention when data is synthetic; keep each field under 120 words. Return strict JSON with "
        "exactly those four string keys."
    )
    facts = {
        "headline": payload["headline"],
        "summary": payload["summary"],
        "observations": payload["observations"],
        "interpretation": payload["interpretation"],
        "confidence": payload["confidence"],
        "limitations": payload["limitations"][:6],
        "is_synthetic": analysis.is_synthetic,
    }
    url = settings.openai_base_url.rstrip("/") + "/chat/completions"
    try:
        async with httpx.AsyncClient(timeout=settings.llm_timeout_seconds) as client:
            response = await client.post(
                url,
                headers={
                    "Authorization": f"Bearer {settings.openai_api_key}",
                    "Content-Type": "application/json",
                },
                json={
                    "model": settings.openai_model,
                    "temperature": 0.2,
                    "response_format": {"type": "json_object"},
                    "messages": [
                        {"role": "system", "content": system_prompt},
                        {"role": "user", "content": json.dumps(facts)},
                    ],
                },
            )
        if response.status_code >= 400:
            return (
                None,
                f"LLM provider returned HTTP {response.status_code}; deterministic explanation used.",
            )
        content = response.json()["choices"][0]["message"]["content"]
        parsed = json.loads(content)
        if not isinstance(parsed, dict):
            return (
                None,
                "LLM returned an invalid payload; deterministic explanation used.",
            )
        allowed = {"headline", "summary", "interpretation", "environmental_relevance"}
        updated = {key: str(parsed[key]) for key in allowed if parsed.get(key)}
        if not updated:
            return (
                None,
                "LLM did not return usable fields; deterministic explanation used.",
            )
        return updated, None
    except Exception as exc:
        logger.warning("LLM narration failed: %s", exc.__class__.__name__)
        return None, "LLM narration failed; deterministic explanation used."


async def build_explanation(
    analysis: Analysis, before: Observation, after: Observation, location: Location
) -> dict[str, Any]:
    payload = _deterministic(analysis, before, after, location)
    llm_fields, llm_error = await _try_llm(payload, analysis)
    if llm_fields:
        payload.update(llm_fields)
        payload["mode"] = "llm"
        payload["engine"] = f"LLM narration · {get_settings().openai_model}"
        payload["note"] = (
            "Narrative fields were rewritten by an optional LLM from the deterministic "
            "analysis facts. Statistics, quality and limitations are unchanged."
        )
    elif llm_error:
        payload["note"] = llm_error
    return payload
